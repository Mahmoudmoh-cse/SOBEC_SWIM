"""PyTorch dataset for AquaIQ's processed SwimXYZ COCO exports.

This module intentionally stays lightweight: it loads the COCO-style output
created by ``scripts/swimxyz/convert_to_coco.py`` and performs only resizing,
normalization, and coordinate scaling. Training augmentations belong in the
future Kaggle training notebooks/configs, not in this local preprocessing layer.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import cv2
import numpy as np

try:
    import torch
    from torch.utils.data import Dataset
except ImportError as exc:  # pragma: no cover - exercised only when torch is absent.
    raise ImportError(
        "SwimXYZCocoDataset requires PyTorch. Install torch in the environment "
        "used for dataset validation or run this module on Kaggle."
    ) from exc


class SwimXYZCocoDataset(Dataset):
    """Load processed SwimXYZ COCO keypoint samples on CPU.

    Parameters
    ----------
    coco_json:
        Path to ``train.json`` or ``val.json`` generated by the converter.
    images_root:
        Directory containing the corresponding exported images.
    image_size:
        Output size as ``(height, width)``. Defaults to RTMPose-style
        ``256 x 192`` input resolution.
    train:
        Whether this dataset is used for training mode. This flag is stored in
        sample metadata only; no heavy augmentation is applied locally.
    normalize:
        Apply ImageNet normalization after converting images to ``[0, 1]``.
    """

    def __init__(
        self,
        coco_json: str | Path,
        images_root: str | Path,
        image_size: tuple[int, int] = (256, 192),
        train: bool = True,
        normalize: bool = True,
    ) -> None:
        self.coco_json = Path(coco_json)
        self.images_root = Path(images_root)
        self.image_size = image_size
        self.train = train
        self.normalize = normalize

        if not self.coco_json.exists():
            raise FileNotFoundError(f"COCO annotation file not found: {self.coco_json}")
        if not self.images_root.exists():
            raise FileNotFoundError(f"Images root not found: {self.images_root}")

        payload = json.loads(self.coco_json.read_text(encoding="utf-8"))
        self.images: list[dict[str, Any]] = list(payload.get("images", []))
        annotations = list(payload.get("annotations", []))

        self.annotations_by_image: dict[int, dict[str, Any]] = {}
        for annotation in annotations:
            image_id = int(annotation.get("image_id", -1))
            current = self.annotations_by_image.get(image_id)
            if current is None or float(annotation.get("area", 0.0)) > float(current.get("area", 0.0)):
                self.annotations_by_image[image_id] = annotation

        self.samples = [
            image
            for image in self.images
            if int(image.get("id", -1)) in self.annotations_by_image
        ]
        if not self.samples:
            raise ValueError(
                f"No image/annotation pairs found in {self.coco_json}. "
                "Run the COCO converter and visual sanity checks first."
            )

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, index: int) -> dict[str, Any]:
        image_info = self.samples[index]
        image_id = int(image_info["id"])
        annotation = self.annotations_by_image[image_id]
        image_path = self.images_root / str(image_info["file_name"])

        image = cv2.imread(str(image_path), cv2.IMREAD_COLOR)
        if image is None:
            raise FileNotFoundError(f"Could not read image: {image_path}")

        original_height, original_width = image.shape[:2]
        target_height, target_width = self.image_size
        scale_x = target_width / float(original_width)
        scale_y = target_height / float(original_height)

        image_rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
        resized = cv2.resize(image_rgb, (target_width, target_height), interpolation=cv2.INTER_LINEAR)
        image_tensor = self._image_to_tensor(resized)

        keypoints = np.asarray(annotation.get("keypoints", []), dtype=np.float32).reshape(-1, 3)
        if keypoints.size:
            visible = keypoints[:, 2] > 0
            keypoints[visible, 0] *= scale_x
            keypoints[visible, 1] *= scale_y
            keypoints[~visible, 0:2] = 0.0

        bbox = np.asarray(annotation.get("bbox", [0.0, 0.0, 0.0, 0.0]), dtype=np.float32)
        if bbox.shape[0] != 4:
            bbox = np.zeros((4,), dtype=np.float32)
        bbox[[0, 2]] *= scale_x
        bbox[[1, 3]] *= scale_y

        metadata = {
            "file_name": image_info.get("file_name"),
            "source_video": image_info.get("source_video"),
            "frame_index": image_info.get("frame_index"),
            "timestamp_sec": image_info.get("timestamp_sec"),
            "original_width": original_width,
            "original_height": original_height,
            "target_width": target_width,
            "target_height": target_height,
            "mode": "train" if self.train else "val",
        }

        return {
            "image": image_tensor,
            "keypoints": torch.from_numpy(keypoints.astype(np.float32)),
            "bbox": torch.from_numpy(bbox.astype(np.float32)),
            "image_id": torch.tensor(image_id, dtype=torch.long),
            "metadata": metadata,
        }

    def _image_to_tensor(self, image_rgb: np.ndarray) -> torch.Tensor:
        image_float = image_rgb.astype(np.float32) / 255.0
        if self.normalize:
            mean = np.asarray([0.485, 0.456, 0.406], dtype=np.float32)
            std = np.asarray([0.229, 0.224, 0.225], dtype=np.float32)
            image_float = (image_float - mean) / std
        image_chw = np.transpose(image_float, (2, 0, 1))
        return torch.from_numpy(image_chw.astype(np.float32))

